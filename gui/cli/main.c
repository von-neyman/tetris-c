// tetris/gui/cli/main.c
/**
 * @file main.c
 * @brief Точка входа в игру (главный цикл интерфейса)
 *
 * Этот файл содержит функцию main(), которая инициализирует ncurses,
 * проверяет размер терминала и запускает основной игровой процесс.
 */

#include "tetris_frontend.h"

/**
 * @brief Главная функция программы
 * @return 0 при успешном завершении
 *
 * Инициализирует библиотеку ncurses, проверяет, что размер терминала
 * достаточен для корректного отображения игры (минимум 40x25),
 * и запускает игровой процесс через функцию gameplay().
 */
int main() {
  initiation_ncurses();
  if (terminal_size_is_correct()) gameplay();
  return 0;
}
// tetris/brick_game/tetris/tetris_objects.h
/**
 * @file tetris_objects.h
 * @brief Внутренние структуры данных библиотеки Тетрис
 *
 * Содержит определения структур, используемых внутри библиотеки:
 * - типы экранов для передачи в интерфейс
 * - состояния конечного автомата
 * - структуру фигуры (тетрамино)
 * - структуру полного состояния игры
 */

#ifndef TETRIS_OBJECTS_H
#define TETRIS_OBJECTS_H

#include "tetris_defines.h"

/**
 * @brief Типы экранов для кодирования в поле pause структуры GameInfo_t
 *
 * Значения передаются из библиотеки в интерфейс через GameInfo_t.pause,
 * чтобы интерфейс знал, какой экран отображать.
 */
typedef enum {
  Screen_Game = 0,   ///< Игровой процесс (не на паузе)
  Screen_Pause = 1,  ///< Игра на паузе
  Screen_Start = 2,  ///< Стартовый экран (ожидание нажатия Start)
  Screen_GameOver = 3  ///< Экран окончания игры
} Screen_t;

/**
 * @brief Состояния конечного автомата игры
 *
 * Описывает все возможные состояния, в которых может находиться игра.
 * Переходы между состояниями определяются действиями пользователя,
 * таймером и событиями (коллизия, удаление линий).
 */
typedef enum {
  GameState_Start,  ///< Стартовое состояние: ожидание нажатия кнопки Start
  GameState_Spawn,  ///< Спавн: создание новой фигуры и проверка коллизии
  GameState_Moving,  ///< Движение: основное игровое состояние, обработка ввода
  GameState_Shifting,  ///< Сдвиг: автоматическое смещение фигуры вниз
  GameState_Attaching,  ///< Соединение: фигура коснулась дна, проверка линий
  GameState_GameOver,  ///< Игра окончена: фигура достигла верхней границы
  GameState_Pause      ///< Пауза: игра приостановлена
} GameState_t;

/**
 * @brief Структура фигуры (тетрамино)
 *
 * Каждая фигура представлена матрицей 4x4, где 1 обозначает наличие блока,
 * а 0 — пустую клетку. Поле size указывает фактический размер фигуры
 * (2 для O, 3 для J/L/S/T/Z, 4 для I).
 */
typedef struct {
  int shape[4][4];  ///< Матрица 4x4: 1 — блок, 0 — пусто
  int size;  ///< Фактический размер фигуры (2, 3 или 4)
} Tetromino;

/**
 * @brief Полное внутреннее состояние игры
 *
 * Содержит всю информацию, необходимую для работы игровой логики:
 * - игровое поле (упавшие блоки)
 * - текущая и следующая фигуры
 * - позиция текущей фигуры
 * - игровая статистика (счет, уровень, рекорд)
 * - параметры скорости (задержка падения, счетчик кадров)
 * - флаги паузы и состояние конечного автомата
 *
 * @note Эта структура доступна только внутри библиотеки.
 *       Интерфейс работает с ней через указатель game.
 */
typedef struct {
  int field[FIELD_HEIGHT][FIELD_WIDTH];  ///< Игровое поле (1 — блок, 0 — пусто)
  Tetromino current;  ///< Текущая падающая фигура
  Tetromino next;  ///< Следующая фигура (показывается в интерфейсе)
  int pos_x;  ///< X-координата текущей фигуры на поле
  int pos_y;  ///< Y-координата текущей фигуры на поле
  int score;  ///< Текущий счет игрока
  int level;  ///< Текущий уровень (1-10)
  int speed;  ///< Текущая скорость (дублирует level)
  int high_score;  ///< Рекорд (максимальный счет)
  int drop_delay;  ///< Задержка падения в кадрах (зависит от уровня)
  int drop_counter;  ///< Счетчик кадров до следующего падения
  Screen_t pause;  ///< Флаг паузы (Screen_Game или Screen_Pause)
  GameState_t state;  ///< Текущее состояние конечного автомата
} GameSession_t;

#endif
// tetris/brick_game/tetris/tetris.h
/**
 * @file tetris.h
 * @brief Публичный API библиотеки игры Тетрис
 *
 * Этот файл содержит типы и функции, доступные внешнему интерфейсу (GUI).
 * Библиотека экспортирует только эти два типа и две функции.
 */

#ifndef TETRIS_H
#define TETRIS_H

#include <stdbool.h>

/**
 * @brief Действия пользователя (нажатия кнопок на консоли BrickGame)
 *
 * Соответствует физическим кнопкам консоли.
 */
typedef enum {
  Start,      ///< Начало игры (кнопка Start)
  Pause,      ///< Пауза (кнопка Pause)
  Terminate,  ///< Завершение игры (кнопка Terminate)
  Left,  ///< Движение фигуры влево (стрелка влево)
  Right,  ///< Движение фигуры вправо (стрелка вправо)
  Up,  ///< Стрелка вверх (не используется в тетрисе)
  Down,  ///< Ускоренное падение фигуры (стрелка вниз)
  Action  ///< Вращение фигуры (кнопка Action / пробел)
} UserAction_t;

/**
 * @brief Структура состояния игры для отрисовки
 *
 * Содержит всю информацию, необходимую интерфейсу для отображения игры.
 * Поле field содержит игровое поле 20x10 с наложенной текущей фигурой.
 * Поле next содержит матрицу 4x4 следующей фигуры.
 * Поле pause кодирует тип экрана (игра, пауза, старт, game over).
 */
typedef struct {
  int **field;  ///< Игровое поле (матрица 20x10) с наложенной текущей фигурой
  int **next;   ///< Следующая фигура (матрица 4x4)
  int score;    ///< Текущий счет игрока
  int high_score;  ///< Рекорд (максимальный счет, сохраняется между запусками)
  int level;  ///< Текущий уровень (1-10, влияет на скорость падения)
  int speed;  ///< Текущая скорость (дублирует level, для удобства интерфейса)
  int pause;  ///< Тип экрана
} GameInfo_t;

/**
 * @brief Передача действия пользователя в библиотеку
 * @param action Действие пользователя (Start, Pause, Terminate, Left, Right,
 * Down, Action)
 * @param hold Флаг зажатия клавиши (в данной реализации не используется)
 *
 * Эта функция вызывается из интерфейса при каждом нажатии клавиши.
 * Она обновляет внутреннее состояние игры в соответствии с действием.
 */
void userInput(UserAction_t action, bool hold);

/**
 * @brief Получение текущего состояния игры для отрисовки
 * @return Структура GameInfo_t, содержащая поле, следующую фигуру, счет и т.д.
 *
 * Эта функция должна вызываться из интерфейса с постоянной частотой (например,
 * каждый кадр). Внутри библиотеки происходит обработка таймера и автоматическое
 * падение фигур.
 */
GameInfo_t updateCurrentState();

#endif